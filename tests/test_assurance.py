"""Assurance checks a reviewer can run offline: no network use at runtime, integrity of bundled artefacts, lock file shape."""
import hashlib
import json
import os
import socket

import pytest

ROOT = os.path.join(os.path.dirname(__file__), "..")
ASSETS = os.path.join(ROOT, "src", "deltat_doctor", "assets")


def test_diagnosis_runs_with_outbound_network_disabled(monkeypatch, tiny_model):
    """Any attempt to open a network connection during parsing, diagnosis or report rendering fails the test."""
    def refuse(*a, **k):
        raise AssertionError("the product tried to open a network connection")
    monkeypatch.setattr(socket.socket, "connect", refuse)
    monkeypatch.setattr(socket, "create_connection", refuse)
    from deltat_doctor.diagnose import diagnose_frame
    from deltat_doctor.report import render_report
    from deltat_doctor.sim.scenarios import make_sample
    import numpy as np
    import pandas as pd
    rng = np.random.default_rng(2)
    s = make_sample(rng, 0, causes=("fouling",), month=7)
    frames = [s.frame] + [make_sample(rng, 0, cfg=s.cfg, causes=("fouling",), month=m).frame for m in (8, 9)]
    d = diagnose_frame(pd.concat(frames, ignore_index=True), model=tiny_model[0]).to_dict()
    assert "<html" in render_report(d, "x", "en").lower()


def test_every_bundled_artefact_has_a_recorded_hash_that_matches():
    card = json.load(open(os.path.join(ASSETS, "model_card.json")))
    for name in sorted(f for f in os.listdir(ASSETS) if f.endswith((".joblib", ".npz"))):
        assert name in card["sha256"], f"{name} has no recorded sha256"
        assert hashlib.sha256(open(os.path.join(ASSETS, name), "rb").read()).hexdigest() == card["sha256"][name], name


def test_lock_file_is_generated_and_fully_hashed():
    path = os.path.join(ROOT, "requirements.lock")
    if not os.path.exists(path):
        pytest.skip("requirements.lock not present")
    text = open(path).read()
    assert text.startswith("# This file is generated by scripts/make_lock.py")
    pins = [ln for ln in text.splitlines() if ln and not ln.startswith((" ", "#")) and "==" in ln]
    assert len(pins) >= 15 and all(ln.rstrip(" \\").count("==") == 1 for ln in pins)
    assert text.count("--hash=sha256:") >= len(pins)
