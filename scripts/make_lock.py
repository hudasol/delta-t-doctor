"""Generate requirements.lock: every runtime dependency (direct and transitive) pinned, with the sha256 of every file PyPI publishes for
that version, so `pip install --require-hashes` accepts the right wheel on any platform.

usage: python scripts/make_lock.py [--constraints ci/constraints.txt] [--extras api,xlsx]

Steps: pip resolves the package's runtime extras under the constraints (`pip install --dry-run --report`, nothing is installed), then the
digests are read from the PyPI JSON API (https://pypi.org/pypi/<name>/<version>/json). pip-compile --generate-hashes gives the same
kind of file but downloads every wheel to hash it, which was not practical on the link available when this was written.
"""
import argparse, datetime, json, os, subprocess, sys, tempfile, urllib.request

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def resolve(extras, constraints):
    with tempfile.TemporaryDirectory() as d:
        rep = os.path.join(d, "report.json")
        cmd = [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet", "--report", rep, "-c", constraints,
               f".[{extras}]"]
        subprocess.run(cmd, cwd=ROOT, check=True)
        with open(rep, encoding="utf-8") as fh:
            items = json.load(fh)["install"]
    return sorted((i["metadata"]["name"], i["metadata"]["version"]) for i in items if i["metadata"]["name"].lower() != "deltat-doctor")


def digests(name, version):
    for attempt in range(5):
        try:
            with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=120) as r:
                data = json.load(r)
            return sorted({u["digests"]["sha256"] for u in data["urls"]})
        except OSError:
            if attempt == 4:
                raise


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--constraints", default="ci/constraints.txt")
    ap.add_argument("--extras", default="api,xlsx")
    ap.add_argument("--out", default="requirements.lock")
    a = ap.parse_args()
    pins = resolve(a.extras, a.constraints)
    lines = ["# This file is generated by scripts/make_lock.py; do not edit by hand.",
             f"# Resolved {datetime.date.today().isoformat()} with pip {__import__('pip').__version__} on Python "
             f"{sys.version.split()[0]}, extras [{a.extras}], constraints {a.constraints}.",
             "# Hashes are the sha256 digests PyPI publishes for every file of each pinned version.", ""]
    for name, version in pins:
        hs = digests(name, version)
        lines.append(f"{name.lower()}=={version} \\")
        lines += [f"    --hash=sha256:{h}" + (" \\" if i < len(hs) - 1 else "") for i, h in enumerate(hs)]
        print(name, version, len(hs), "hashes", flush=True)
    open(os.path.join(ROOT, a.out), "w", newline="\n").write("\n".join(lines) + "\n")
    print("wrote", a.out, len(pins), "packages")


if __name__ == "__main__":
    main()
